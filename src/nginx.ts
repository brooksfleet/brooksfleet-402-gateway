import { DEFAULT_CHARGED_PURPOSES, crawlersFor, type CrawlerPurpose } from './crawlers.js';

export interface NginxMapOptions {
  /** nginx variable set to 1 for a charged crawler. Default `ai_training_crawler`. */
  readonly variable?: string;
  readonly purposes?: readonly CrawlerPurpose[];
}

const VARIABLE = /^[a-z_][a-z0-9_]*$/;

/** Regex metacharacters escaped so a token matches literally in nginx's `~*`. */
function escapeRegex(token: string): string {
  return token.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * An nginx `map` (http context, e.g. `/etc/nginx/conf.d/`) that sets
 * `$<variable>` to 1 for charged crawlers. Use it in a server block with
 * `if ($ai_training_crawler) { return 402; }` — see the README.
 */
export function nginxMap(options: NginxMapOptions = {}): string {
  const { variable = 'ai_training_crawler', purposes = DEFAULT_CHARGED_PURPOSES } = options;
  if (!VARIABLE.test(variable)) throw new Error(`invalid nginx variable name: ${variable}`);
  const tokens = crawlersFor(purposes).flatMap((c) => c.userAgents);
  return [
    '# Generated by brooksfleet-402-gateway — regenerate, do not edit.',
    `map $http_user_agent $${variable} {`,
    '    default 0;',
    ...tokens.map((t) => `    ~*${escapeRegex(t)} 1;`),
    '}',
    '',
  ].join('\n');
}
